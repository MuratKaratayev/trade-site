// Строгий перевод: если в русской версии появится позиция без перевода — сборка упадёт, а не покажет русский текст.
function tr(map: Record<string, string> | undefined, s: string, where: string): string {
  const v = map?.[s];
  if (v === undefined) throw new Error(`Нет казахского перевода (${where}): «${s}»`);
  return v;
}

export const products: Product[] = ruProducts.map((p) => {
  const k = kkProducts[p.slug];
  if (!k) throw new Error(`Нет казахского перевода раздела ${p.slug}`);
  return {
    ...p,
    title: k.title,
    summary: k.summary,
    description: k.description,
    items: p.items.map((it) => ({
      name: k.names ? tr(k.names, it.name, p.slug) : it.name,
      note: it.note ? tr(k.notes, it.note, p.slug) : undefined,
    })),
  };
});

