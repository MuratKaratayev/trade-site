// Мягкие переносы (U+00AD) для длинных слов в заголовках. Unbounded очень широкий, и на узких экранах
// такие слова не помещаются в строку. CSS hyphens:auto зависит от словарей браузера (на части платформ
// для русского их нет — слово рвётся без дефиса), поэтому точки переноса заданы явно, по слогам.
// Применяется только при выводе заголовков, исходные строки (title, JSON-LD) не меняются.
// Только слова, которые при 360 px не помещаются в строку целиком: иначе браузер переносит
// «жадно» и рвёт слова, которые могли бы просто уйти на следующую строку.
const DICT: Record<string, string> = {
  промышленной: 'про-мыш-лен-ной',
  автоматизации: 'ав-то-ма-ти-за-ции',
  Микропроцессорные: 'Мик-ро-про-цес-сор-ные',
  микропроцессорные: 'мик-ро-про-цес-сор-ные',
  инжиниринговых: 'ин-жи-ни-рин-го-вых',
  // Казахская версия: слова, которые при 320 px не помещаются в строку заголовка (проверено замером)
  Өнеркәсіптік: 'Ө-нер-кә-сіп-тік',
  автоматтандыру: 'ав-то-мат-тан-ды-ру',
  Автоматтандыру: 'Ав-то-мат-тан-ды-ру',
  Микропроцессорлық: 'Мик-ро-про-цес-сор-лық',
  микропроцессорлық: 'мик-ро-про-цес-сор-лық',
  Сертификаттар: 'Сер-ти-фи-кат-тар',
};

const SHY = '­';
const RE = new RegExp(`(?<![\\p{L}])(${Object.keys(DICT).join('|')})(?![\\p{L}])`, 'gu');

export function hyphenate(text: string): string {
  return text.replace(RE, (w) => DICT[w].replaceAll('-', SHY));
}
